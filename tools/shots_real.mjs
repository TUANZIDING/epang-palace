import { chromium } from 'playwright-core'
import { resolve } from 'node:path'
const OUT = resolve('../shots')
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } })
page.on('pageerror', (e) => console.log('PAGE ERROR', e.message))
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 300)) })
await page.goto('file://' + resolve('../index.html') + (process.argv[2] ? '?q=' + process.argv[2] : ''), { waitUntil: 'load', timeout: 120000 })
await page.waitForFunction(() => window.__app?.ready, null, { timeout: 180000 })
await page.evaluate(() => window.__app.skipIntro())
const ft = () => page.evaluate(() => new Promise((r) => { const t = performance.now(); requestAnimationFrame(() => requestAnimationFrame(() => r((performance.now() - t) / 2))) }))
const shot = async (name, js, ms = 3500) => { await page.evaluate(js); await page.waitForTimeout(ms); const f = await ft(); await page.screenshot({ path: `${OUT}/${name}.png` }); console.log('shot', name, 'frame', f.toFixed(0), 'ms') }
console.log(JSON.stringify(await page.evaluate(() => window.__app.info())))
await shot('01_overview', () => { __app.snap({ explode: 0, cut: 0, labels: 0 }); __app.setHour(9.5); __app.setView('overview') }, 4500)
await shot('20_hero_grand', () => { __app.setHour(16.6); __app.cine(true, 64); __app.setView('heroAxis') })
await shot('21_axis_approach', () => { __app.cine(true, 40); __app.setView('axis') })
await page.evaluate(() => { __app.cine(false); __app.setHour(10) })
await shot('19_layers_step1_full', () => { __app.setView({ pos: [-260, 150, 140], target: [0, 18, -100] }); __app.peel(0); __app.settleLayers() })
await shot('19_layers_step8_explode', () => { __app.snap({ explode: 1 }); __app.setView('explode') })
await page.evaluate(() => { __app.snap({ explode: 0 }); __app.settleLayers(); __app.setWalk(true) })
await shot('14_walk_interior_throne', () => __app.walkTo(0, -98, 0, 0.06))
await shot('17_decor_throne', () => __app.walkTo(0, -104, 0, 0.08))
console.log('walk', await page.evaluate(() => { __app.walkTo(0, 150, 0, 0); return __app.simWalk(['KeyW'], 6) }))
await page.evaluate(() => __app.setWalk(false))
await shot('22_cut_labels', () => { __app.snap({ cut: 1, labels: 1 }); __app.setView('cut') })
await browser.close()
